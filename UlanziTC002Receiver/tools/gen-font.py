#!/usr/bin/env python3
"""Render DejaVu Sans Bold to a 1-bit bitmap font with 12 px caps in a 16-row cell -> src/Font.h.

Row 0 blank, caps rows 1..12, descenders rows 13..15. Proportional widths (advance from the TTF,
widened when the ink sticks out). Glyphs: printable ASCII plus the Latin-1 letters Dutch needs.
Run inside the build container: python3 tools/gen-font.py        (writes src/Font.h)
                                 python3 tools/gen-font.py --check (fails when Font.h is stale)
"""
import pathlib
import sys

from PIL import Image, ImageDraw, ImageFont

TTF = "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"
OUT = pathlib.Path(__file__).resolve().parents[1] / "src/Font.h"
CELL_H, CAP_H, BASELINE = 16, 12, 13  # baseline y: caps occupy rows 1..12, descenders 13..15
CHARS = [chr(c) for c in range(32, 127)] + list("¡¿ÀÁÂÃÄÅÆÇÈÉÊËÌÍÎÏÑÒÓÔÕÖØÙÚÛÜÝßàáâãäåæçèéêëìíîïñòóôõöøùúûüýÿ€")


def cap_height(font):
    img = Image.new("L", (64, 64), 0)
    ImageDraw.Draw(img).text((8, 40), "H", font=font, fill=255, anchor="ls")
    rows = [y for y in range(64) if any(img.getpixel((x, y)) > 127 for x in range(64))]
    return rows[-1] - rows[0] + 1


def pick_size():
    for size in range(10, 30):
        if cap_height(ImageFont.truetype(TTF, size)) >= CAP_H:
            return size
    sys.exit("no size gives 12 px caps")


def render(font, ch):
    adv = max(1, round(font.getlength(ch)))
    img = Image.new("L", (adv + 8, CELL_H), 0)
    ImageDraw.Draw(img).text((0, BASELINE), ch, font=font, fill=255, anchor="ls")
    cols = [x for x in range(img.width) if any(img.getpixel((x, y)) > 127 for y in range(CELL_H))]
    width = min(16, max(adv, (cols[-1] + 1) if cols else 0))
    rows = [sum(1 << x for x in range(width) if img.getpixel((x, y)) > 127) for y in range(CELL_H)]
    return width, rows


def main():
    font = ImageFont.truetype(TTF, pick_size())
    assert cap_height(font) == CAP_H, cap_height(font)
    glyphs = sorted((ord(c),) + render(font, c) for c in CHARS)
    lines = [
        "// Generated by tools/gen-font.py from DejaVu Sans Bold. Do not edit.",
        "#pragma once",
        "#include <stdint.h>",
        "#define KIEP_FONT_HEIGHT 16",
        "#define KIEP_GLYPH_GAP 1",
        "// rows[y] bit x set => pixel (x, y) lit; x = 0 is the leftmost column. Sorted by codepoint.",
        "struct KiepGlyph { uint32_t codepoint; uint8_t width; uint16_t rows[16]; };",
        "static const KiepGlyph KIEP_GLYPHS[] = {",
    ]
    for cp, w, rows in glyphs:
        lines.append(f"  {{{cp}, {w}, {{{', '.join(str(r) for r in rows)}}}}}, // {chr(cp)!r}")
    lines += ["};", f"static const int KIEP_GLYPH_COUNT = {len(glyphs)};", ""]
    text = "\n".join(lines)
    if "--check" in sys.argv:
        sys.exit(0 if OUT.exists() and OUT.read_text() == text else "Font.h out of date: run tools/gen-font.py")
    OUT.write_text(text)
    print("wrote", OUT, len(glyphs), "glyphs, font size", font.size)


if __name__ == "__main__":
    main()
